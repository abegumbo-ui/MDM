// Generates src/icons.js: the dashboard's home-screen icon (white shield on indigo) as PNGs, with
// no image libraries. Run with: node tools/make-icons.mjs
import fs from "node:fs";
import zlib from "node:zlib";

const BG = [0x4f, 0x46, 0xe5];
const FG = [0xff, 0xff, 0xff];
// The shield glyph (same shape as the dashboard's logo), in a 24x24 box.
const SHIELD = [[12, 1], [21, 5], [21, 11], [18, 17], [12, 23], [6, 17], [3, 11], [3, 5]];

function inside(poly, x, y) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}

function crc32(buf) {
  let c, crc = 0xffffffff;
  for (let n = 0; n < buf.length; n++) {
    c = (crc ^ buf[n]) & 0xff;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    crc = (crc >>> 8) ^ c;
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}

function png(size) {
  const scale = (size * 0.56) / 24; // shield fills ~56% of the icon: safe inside a maskable crop
  const off = (size - 24 * scale) / 2;
  const SS = 3; // 3x3 supersampling for smooth edges
  const raw = Buffer.alloc((size * 3 + 1) * size);
  for (let y = 0; y < size; y++) {
    raw[y * (size * 3 + 1)] = 0;
    for (let x = 0; x < size; x++) {
      let hit = 0;
      for (let sy = 0; sy < SS; sy++)
        for (let sx = 0; sx < SS; sx++) {
          const gx = (x + (sx + 0.5) / SS - off) / scale;
          const gy = (y + (sy + 0.5) / SS - off) / scale;
          if (inside(SHIELD, gx, gy)) hit++;
        }
      const t = hit / (SS * SS);
      for (let k = 0; k < 3; k++) raw[y * (size * 3 + 1) + 1 + x * 3 + k] = Math.round(BG[k] * (1 - t) + FG[k] * t);
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // RGB
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", zlib.deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const out = `// Generated by tools/make-icons.mjs -- do not edit by hand.
export const ICON_192 = "${png(192).toString("base64")}";
export const ICON_512 = "${png(512).toString("base64")}";
`;
fs.writeFileSync(new URL("../src/icons.js", import.meta.url), out);
console.log("wrote src/icons.js", out.length, "bytes");
